"""Pure parsing of one module's files into what the index stores.

Everything here takes file contents as strings, never paths, so it is tested with literal source.
"""

import ast
import re
from collections.abc import Mapping
from dataclasses import dataclass, field
from enum import StrEnum
from pathlib import PurePosixPath

# Bump whenever parsing changes what it extracts: the next index run then reparses every module
# instead of only those whose files changed.
PARSER_VERSION = 3

# readme/ fragments kept for search. CONTRIBUTORS/CREDITS/HISTORY/INSTALL are people and
# changelog, and maintainers come from the manifest.
README_SECTIONS = ("description", "usage", "configure", "roadmap", "context")

# Python files under these directories never declare the module's models: test-only fake models
# and migration scripts would show up as models the module doesn't really touch.
NON_MODEL_DIRS = frozenset({"tests", "migrations", "upgrades"})

# A class is an Odoo model only if it subclasses one of these. Connector `Component` and
# `Datamodel` classes also set `_name`/`_inherit` (665 such classes across OCA 16.0-19.0) but
# aren't models.
MODEL_BASES = frozenset({"Model", "TransientModel", "AbstractModel"})

# Marks a README.rst generated by OCA's tooling; its description sits between the badge block and
# the table of contents.
GENERATED_README_MARK = "oca-gen-addon-readme"

RELATIONAL_TYPES = frozenset({"Many2one", "One2many", "Many2many"})

# Positional index of the `string` label in each field constructor's signature, for fields that
# take other positional arguments first. E.g. One2many(comodel_name, inverse_name, string).
STRING_POSITION = {
    "Many2one": 1,
    "One2many": 2,
    "Many2many": 4,
    "Selection": 1,
    "Reference": 1,
}


class TouchKind(StrEnum):
    DEFINE = "define"  # `_name` a model that isn't among its own `_inherit`: a new model
    INHERIT = "inherit"  # extends an existing model in place
    MIXIN = "mixin"  # pulled in through `_inherit` alongside the class's own model
    DELEGATE = "delegate"  # `_inherits` delegation target


@dataclass(frozen=True)
class ModelTouch:
    model: str
    kind: TouchKind
    model_type: str  # Model, TransientModel or AbstractModel
    description: str | None
    file: str


@dataclass(frozen=True)
class FieldDef:
    model: str
    name: str
    type: str
    comodel: str | None
    string: str | None
    is_related: bool
    is_computed: bool


@dataclass
class ModuleInfo:
    name: str
    title: str
    summary: str | None = None
    readme: dict[str, str] = field(default_factory=dict)
    category: str | None = None
    license: str | None = None
    author: str | None = None
    website: str | None = None
    module_version: str | None = None
    development_status: str | None = None
    installable: bool = True
    application: bool = False
    auto_install: bool = False
    depends: list[str] = field(default_factory=list)
    python_deps: list[str] = field(default_factory=list)
    bin_deps: list[str] = field(default_factory=list)
    maintainers: list[str] = field(default_factory=list)
    models: list[ModelTouch] = field(default_factory=list)
    fields: list[FieldDef] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)


def is_model_source(relpath: str) -> bool:
    """Whether a module-relative path is a Python file that can declare the module's models."""
    path = PurePosixPath(relpath)
    return path.suffix == ".py" and not NON_MODEL_DIRS.intersection(path.parts[:-1])


def parse_module(
    name: str,
    manifest: str,
    readme_files: Mapping[str, str],
    readme_rst: str | None,
    python_files: Mapping[str, str],
) -> ModuleInfo:
    """Parse one module.

    A broken file is recorded in `errors` and skipped; the rest of the module is still parsed.

    Args:
        name: Module directory name.
        manifest: `__manifest__.py` source.
        readme_files: `readme/` file name -> contents, e.g. {"DESCRIPTION.md": "..."}.
        readme_rst: The module's `README.rst`, used for the description only when `readme/` has
            no DESCRIPTION (true of 70 of 8,517 modules, mostly older hand-written READMEs).
        python_files: Module-relative path -> source, already filtered with `is_model_source`.

    Returns:
        The parsed module.
    """
    info = ModuleInfo(name=name, title=name)
    _apply_manifest(info, manifest)
    info.readme = _readme_sections(readme_files)
    if "description" not in info.readme and readme_rst:
        info.readme["description"] = _readme_rst_description(readme_rst)
    for relpath, source in sorted(python_files.items()):
        try:
            tree = ast.parse(source)
        except SyntaxError as e:
            info.errors.append(f"{relpath}: {e}")
            continue
        for node in ast.walk(tree):
            if isinstance(node, ast.ClassDef):
                touches, fields = _class_model(node, relpath)
                info.models.extend(touches)
                info.fields.extend(fields)
    return info


def _apply_manifest(info: ModuleInfo, source: str) -> None:
    try:
        manifest = ast.literal_eval(source)
    except (ValueError, SyntaxError) as e:
        info.errors.append(f"__manifest__.py: {e}")
        return
    info.title = manifest.get("name", info.name)
    # 28 OCA manifests spell it "Summary".
    info.summary = manifest.get("summary") or manifest.get("Summary")
    info.category = manifest.get("category")
    info.license = manifest.get("license")
    info.author = manifest.get("author")
    info.website = manifest.get("website")
    info.module_version = manifest.get("version")
    info.development_status = manifest.get("development_status")
    info.installable = bool(manifest.get("installable", True))
    info.application = bool(manifest.get("application", False))
    # A list means "auto-install once these are installed"; either way it auto-installs.
    info.auto_install = bool(manifest.get("auto_install", False))
    info.depends = list(manifest.get("depends", []))
    external = manifest.get("external_dependencies", {})
    info.python_deps = list(external.get("python", []))
    info.bin_deps = list(external.get("bin", []))
    info.maintainers = list(manifest.get("maintainers", []))


def _readme_sections(files: Mapping[str, str]) -> dict[str, str]:
    sections = {}
    # 16.0 mixes .md and .rst fragments. Sorted so a fragment present in both formats resolves
    # the same way every run.
    for filename, text in sorted(files.items()):
        path = PurePosixPath(filename)
        section = path.stem.lower()
        if section in README_SECTIONS and path.suffix in (".md", ".rst") and text.strip():
            sections[section] = text.strip()
    return sections


def _readme_rst_description(text: str) -> str:
    if GENERATED_README_MARK in text:
        text = text.split("**Table of contents**", 1)[0]
    else:
        # Older hand-written READMEs: everything from "Bug Tracker" on is shared boilerplate.
        text = text.split("\nBug Tracker\n", 1)[0]
    return clean_markup(text)


def clean_markup(text: str) -> str:
    """Strip readme markup that carries no meaning: RST comments and directives (badges,
    images, the generated-file banner), heading underlines, image and link syntax (link text is
    kept), HTML tags and URLs.

    Measured on the search benchmark: embedding cleaned text raised MRR from 0.44 to 0.48.
    """
    lines, in_directive = [], False
    for line in text.splitlines():
        if line.startswith(".."):  # RST comment or directive; indented lines continue it
            in_directive = True
            continue
        if in_directive and (line.startswith((" ", "\t")) or not line.strip()):
            continue
        in_directive = False
        if re.fullmatch(r"\s*[!=~\-^*#`'_.]{3,}\s*", line) or line.lstrip().startswith("|badge"):
            continue
        lines.append(line)
    text = "\n".join(lines)
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", text)  # markdown images
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)  # markdown links -> text
    text = re.sub(r"`([^`<]+?)\s*<[^>]+>`_+", r"\1", text)  # RST links -> text
    text = re.sub(r"<[^>]+>", " ", text)  # HTML tags
    text = re.sub(r"https?://\S+", "", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def _class_model(cls: ast.ClassDef, relpath: str) -> tuple[list[ModelTouch], list[FieldDef]]:
    model_type = next((b for b in map(_base_name, cls.bases) if b in MODEL_BASES), None)
    if model_type is None:
        return [], []
    attrs, field_calls = {}, []
    for stmt in cls.body:
        target, value = _simple_assignment(stmt)
        if target is None:
            continue
        if target in ("_name", "_inherit", "_inherits", "_description"):
            attrs[target] = _literal(value)
        elif isinstance(value, ast.Call) and _is_field_constructor(value.func):
            field_calls.append((target, value))

    own_name = attrs.get("_name") if isinstance(attrs.get("_name"), str) else None
    inherit = attrs.get("_inherit")
    inherit = (
        [inherit] if isinstance(inherit, str) else [i for i in inherit or () if isinstance(i, str)]
    )
    model = own_name or (inherit[0] if inherit else None)
    if model is None:
        return [], []
    description = attrs.get("_description")
    description = description if isinstance(description, str) else None

    touches = [
        ModelTouch(
            model,
            TouchKind.INHERIT if model in inherit else TouchKind.DEFINE,
            model_type,
            description,
            relpath,
        )
    ]
    touches += [
        ModelTouch(other, TouchKind.MIXIN, model_type, None, relpath)
        for other in inherit
        if other != model
    ]
    delegates = attrs.get("_inherits")
    if isinstance(delegates, dict):
        touches += [
            ModelTouch(target, TouchKind.DELEGATE, model_type, None, relpath)
            for target in delegates
            if isinstance(target, str)
        ]
    fields = [_field_def(model, target, call) for target, call in field_calls]
    return touches, fields


def _base_name(base: ast.expr) -> str | None:
    # `models.Model` and a bare imported `Model` both appear in OCA code.
    if isinstance(base, ast.Attribute):
        return base.attr
    if isinstance(base, ast.Name):
        return base.id
    return None


def _simple_assignment(stmt: ast.stmt) -> tuple[str | None, ast.expr | None]:
    if (
        isinstance(stmt, ast.Assign)
        and len(stmt.targets) == 1
        and isinstance(stmt.targets[0], ast.Name)
    ):
        return stmt.targets[0].id, stmt.value
    if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name) and stmt.value:
        return stmt.target.id, stmt.value
    return None, None


def _is_field_constructor(func: ast.expr) -> bool:
    # `fields.Char(...)`, not `fields.Command.create(...)` or `fields.Date.today()`.
    return (
        isinstance(func, ast.Attribute)
        and isinstance(func.value, ast.Name)
        and func.value.id == "fields"
        and func.attr[:1].isupper()
    )


def _literal(node: ast.expr | None):
    try:
        return ast.literal_eval(node)
    except (ValueError, TypeError, SyntaxError):
        return None


def _str_arg(call: ast.Call, position: int, keyword: str) -> str | None:
    for kw in call.keywords:
        if kw.arg == keyword:
            value = _literal(kw.value)
            return value if isinstance(value, str) else None
    if len(call.args) > position:
        value = _literal(call.args[position])
        return value if isinstance(value, str) else None
    return None


def _field_def(model: str, name: str, call: ast.Call) -> FieldDef:
    field_type = call.func.attr
    relational = field_type in RELATIONAL_TYPES
    keywords = {kw.arg for kw in call.keywords}
    return FieldDef(
        model=model,
        name=name,
        type=field_type,
        comodel=_str_arg(call, 0, "comodel_name") if relational else None,
        string=_str_arg(call, STRING_POSITION.get(field_type, 0), "string"),
        is_related="related" in keywords,
        is_computed="compute" in keywords,
    )
